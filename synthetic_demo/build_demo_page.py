"""Build a self-contained HTML demo (inline SVG, no external assets) from synthetic RMS data.

Usage: python synthetic_demo/build_demo_page.py site/index.html
No plant data is read: everything comes from rms_alarms.synthetic_rms (seeded).
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rms_alarms import ALARM_MM_S, ALERT_MM_S, ZONES, classify, first_crossings, synthetic_rms  # noqa: E402

COLORS = {"A": "#22D3EE", "B": "#a8a29e", "C": "#F59E0B", "D": "#78716c"}
W, H, PAD = 760, 320, 44
YMAX = 10.0


def _points(series, n: int) -> str:
    step = max(1, n // 400)
    pts = []
    for i in range(0, n, step):
        x = PAD + (W - 2 * PAD) * i / (n - 1)
        y = H - PAD - (H - 2 * PAD) * min(series.iloc[i], YMAX) / YMAX
        pts.append(f"{x:.1f},{y:.1f}")
    return " ".join(pts)


def build_html(days: int = 7, seed: int = 42, fault_zone: str = "C") -> str:
    df = synthetic_rms(days=days, seed=seed, fault_zone=fault_zone)
    cross = first_crossings(classify(df))
    n = len(df)

    def yline(v: float) -> float:
        return H - PAD - (H - 2 * PAD) * v / YMAX

    lines = "".join(
        f'<polyline fill="none" stroke="{COLORS[z]}" stroke-width="1.6" points="{_points(df[z], n)}"/>'
        for z in ZONES
    )
    thresholds = (
        f'<line x1="{PAD}" x2="{W - PAD}" y1="{yline(ALERT_MM_S):.1f}" y2="{yline(ALERT_MM_S):.1f}" stroke="#F59E0B" stroke-dasharray="6 4"/>'
        f'<text x="{W - PAD}" y="{yline(ALERT_MM_S) - 4:.1f}" text-anchor="end" fill="#F59E0B" font-size="12">alert {ALERT_MM_S} mm/s</text>'
        f'<line x1="{PAD}" x2="{W - PAD}" y1="{yline(ALARM_MM_S):.1f}" y2="{yline(ALARM_MM_S):.1f}" stroke="#ef4444" stroke-dasharray="6 4"/>'
        f'<text x="{W - PAD}" y="{yline(ALARM_MM_S) - 4:.1f}" text-anchor="end" fill="#ef4444" font-size="12">alarm {ALARM_MM_S} mm/s</text>'
    )
    legend = "".join(
        f'<span><i style="background:{COLORS[z]}"></i>Zone {z}</span>' for z in ZONES
    )
    rows = "".join(
        f"<tr><td>Zone {z}</td><td>{t['alert'] or '—'}</td><td>{t['alarm'] or '—'}</td></tr>"
        for z, t in cross.items()
    )
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Aenergia — Synthetic vibration demo</title>
<style>
body{{font-family:system-ui,sans-serif;background:#1C1917;color:#f5f5f4;margin:0;padding:24px;max-width:820px;margin:auto}}
h1{{color:#F59E0B;margin-bottom:0}} .tag{{color:#22D3EE;margin-top:4px}}
svg{{width:100%;height:auto;background:#292524;border-radius:8px}}
.legend span{{margin-right:16px;font-size:14px}} .legend i{{display:inline-block;width:12px;height:12px;margin-right:6px;border-radius:2px}}
table{{border-collapse:collapse;width:100%;margin-top:16px}} td,th{{border-bottom:1px solid #44403c;padding:6px;text-align:left}}
small{{color:#a8a29e}}
</style></head><body>
<h1>Predict before it fails</h1>
<p class="tag">Vibration RMS per zone — synthetic data, seed {seed}</p>
<svg viewBox="0 0 {W} {H}" role="img" aria-label="Vibration RMS per zone over {days} days with alert and alarm thresholds">
<line x1="{PAD}" x2="{PAD}" y1="{PAD}" y2="{H - PAD}" stroke="#78716c"/><line x1="{PAD}" x2="{W - PAD}" y1="{H - PAD}" y2="{H - PAD}" stroke="#78716c"/>
<text x="8" y="{PAD}" fill="#a8a29e" font-size="12">mm/s</text><text x="{W // 2}" y="{H - 10}" fill="#a8a29e" font-size="12" text-anchor="middle">{days} days (1-min samples)</text>
{thresholds}{lines}</svg>
<p class="legend">{legend}</p>
<p>Zone {fault_zone} drifts upward during the last 2 days. A 10-minute rolling mean crosses the alert level first, then the alarm level, hours before a hard failure would show up.</p>
<table><tr><th>Zone</th><th>First alert</th><th>First alarm</th></tr>{rows}</table>
<p><small>All data is generated by <code>synthetic_demo/rms_alarms.py</code>; thresholds are illustrative, not from any real machine. No plant data is used or stored. — Aenergia ⚡</small></p>
</body></html>
"""


if __name__ == "__main__":
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "site/index.html")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_html(), encoding="utf-8")
    print(f"wrote {out}")
